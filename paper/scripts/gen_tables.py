#!/usr/bin/env python3
import json
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.dirname(HERE)
ROOT = os.path.dirname(PAPER)                       # AirgapForge/
AI = os.path.dirname(os.path.dirname(ROOT))         # AI/
STATS = os.environ.get("CYBERLLM_STATS",
                       os.path.join(AI, "Analysis", "CyberLLMInstruct", "statistics.json"))
OFFENSIVE = os.path.join(ROOT, "offensive", "data")
TABLES = os.path.join(PAPER, "tables")


def esc(s):
    return str(s).replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")


def wrap(caption, label, colspec, header, body_rows, star=False):
    env = "table*" if star else "table"
    out = ["% AUTO-GENERATED by gen_tables.py -- do not edit",
           f"\\begin{{{env}}}[t]", "\\centering", "\\small",
           f"\\caption{{{caption}}}", f"\\label{{{label}}}",
           f"\\begin{{tabular}}{{{colspec}}}", "\\hline",
           header + " \\\\", "\\hline"]
    out += [r + " \\\\" for r in body_rows]
    out += ["\\hline", "\\end{tabular}", f"\\end{{{env}}}", ""]
    return "\n".join(out)


def count_lines(path):
    if not os.path.exists(path):
        return None
    with open(path, "rb") as f:
        return sum(1 for _ in f)


def gen_dataset_tables(stats):
    meta, basic, text = stats["metadata"], stats["basic"], stats["text"]
    dom, qual = stats["domain"], stats["quality"]

    # Basic
    rows = [
        f"Total samples & {basic['total_samples']:,}",
        f"Unique samples & {basic['unique_samples']:,}",
        f"Duplicate rate & {basic['duplicate_rate']*100:.2f}\\%",
        f"File size (MB) & {meta['file_size_mb']:.2f}",
        f"Total tokens & {text['total_tokens']:,}",
        f"Vocabulary size & {text['vocabulary_size']:,}",
        f"Code-bearing samples & {qual['code_percentage']:.1f}\\%",
    ]
    with open(os.path.join(TABLES, "dataset_basic.tex"), "w") as f:
        f.write(wrap("Defensive instruction dataset: basic statistics.",
                     "tab:dataset-basic", "lr",
                     "\\textbf{Metric} & \\textbf{Value}", rows))

    # Text length
    def r(name, key):
        return (f"{name} & {text[key+'_mean']:.1f} & {text[key+'_median']:.1f} "
                f"& {text[key+'_std']:.1f} & {text[key+'_p95']:.0f}")
    rows = [r("Tokens", "token_counts"), r("Words", "word_counts"),
            r("Characters", "char_lengths")]
    with open(os.path.join(TABLES, "dataset_text.tex"), "w") as f:
        f.write(wrap("Defensive dataset text-length statistics per sample. "
                     "The large mean/median gap reflects a strongly bimodal "
                     "distribution (short prompts, long technical answers).",
                     "tab:dataset-text", "lrrrr",
                     "\\textbf{Unit} & \\textbf{Mean} & \\textbf{Median} "
                     "& \\textbf{Std} & \\textbf{P95}", rows))

    # Domains
    names = {"defense": "Defense", "forensics": "Forensics", "threat": "Threat intel",
             "vulnerability": "Vulnerability", "attack": "Attack", "network": "Network",
             "crypto": "Cryptography", "compliance": "Compliance"}
    pairs = []
    for k in names:
        pk = f"domain_{k}_percentage"
        if pk in dom:
            pairs.append((names[k], dom[pk]))
    pairs.sort(key=lambda x: -x[1])
    rows = [f"{n} & {p:.1f}\\%" for n, p in pairs]
    with open(os.path.join(TABLES, "dataset_domains.tex"), "w") as f:
        f.write(wrap("Domain coverage of the defensive dataset (keyword-based, "
                     "overlapping). Compliance is the clear coverage gap.",
                     "tab:dataset-domains", "lr",
                     "\\textbf{Domain} & \\textbf{Coverage}", rows))


def gen_offensive_sizes():
    splits = [("Train", "train.jsonl"), ("Validation", "valid.jsonl"),
              ("Test", "test.jsonl")]
    rows = []
    total = 0
    for name, fn in splits:
        n = count_lines(os.path.join(OFFENSIVE, fn))
        if n is None:
            continue
        total += n
        rows.append(f"{name} & {n:,}")
    rows.append(f"\\textbf{{Total}} & \\textbf{{{total:,}}}")
    with open(os.path.join(TABLES, "offensive_sizes.tex"), "w") as f:
        f.write(wrap("Offensive exploitation SFT dataset, synthesized by an "
                     "abliterated model over the public CyberNative "
                     "Code\\_Vulnerability\\_Security\\_DPO corpus.",
                     "tab:offensive-sizes", "lr",
                     "\\textbf{Split} & \\textbf{Records}", rows))


def load_yaml(path):
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return yaml.safe_load(f)


def gen_hyperparams():
    sft = load_yaml(os.path.join(ROOT, "training",
                                 "CyberLLMinstruct_qwen3-30b-3ab-thinking-2507.yaml"))
    dpo = load_yaml(os.path.join(ROOT, "offensive", "preference", "dpo_config.yaml"))

    # Three-column table: parameter | SFT | DPO
    def g(d, *keys, default="--"):
        if not d:
            return default
        for k in keys:
            if k in d:
                return d[k]
        return default

    sft_lp = (sft or {}).get("lora_parameters", {})
    dpo_lp = (dpo or {}).get("lora_parameters", {})
    table = [
        ("Fine-tune type", g(sft, "fine_tune_type"), g(dpo, "train_mode")),
        ("LoRA rank", sft_lp.get("rank", "--"), dpo_lp.get("rank", "--")),
        ("LoRA scale", sft_lp.get("scale", "--"), dpo_lp.get("scale", "--")),
        ("LoRA dropout", sft_lp.get("dropout", "--"), dpo_lp.get("dropout", "--")),
        ("Layers tuned", g(sft, "num_layers"),
         "all" if g(dpo, "num_layers") == -1 else g(dpo, "num_layers")),
        ("Batch size", g(sft, "batch_size"), g(dpo, "batch_size")),
        ("Grad accumulation", g(sft, "gradient_accumulation_steps"),
         g(dpo, "gradient_accumulation_steps")),
        ("Learning rate", g(sft, "learning_rate"), g(dpo, "learning_rate")),
        ("Iterations", g(sft, "iters"), g(dpo, "iters")),
        ("Max seq length", g(sft, "max_seq_length"), g(dpo, "max_seq_length")),
        ("Optimizer", g(sft, "optimizer"), g(dpo, "optimizer")),
        ("DPO $\\beta$", "--", g(dpo, "beta")),
        ("Seed", g(sft, "seed"), g(dpo, "seed")),
    ]
    body = [f"{esc(name)} & {esc(a)} & {esc(b)}" for name, a, b in table]
    with open(os.path.join(TABLES, "hyperparams.tex"), "w") as f:
        f.write(wrap("Fine-tuning hyperparameters, read from the released training "
                     "configs. SFT column: LoRA instruction tuning; DPO column: "
                     "preference tuning.",
                     "tab:hyperparams", "lrr",
                     "\\textbf{Parameter} & \\textbf{SFT} & \\textbf{DPO}", body))


def main():
    os.makedirs(TABLES, exist_ok=True)
    with open(STATS) as f:
        stats = json.load(f)
    gen_dataset_tables(stats)
    gen_offensive_sizes()
    gen_hyperparams()
    print("gen_tables: dataset_basic, dataset_text, dataset_domains, "
          "offensive_sizes, hyperparams -> tables/")


if __name__ == "__main__":
    main()
