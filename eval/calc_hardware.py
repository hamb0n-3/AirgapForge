#!/usr/bin/env python3
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RESULTS = os.path.join(HERE, "results")
PAPER_TABLES = os.path.join(ROOT, "paper", "tables")

BPW = {"Q4_K_M": 4.83, "MXFP4": 4.25}
CTX = 8192
OVERHEAD_GB = 0.7

# US used/consumer prices, surveyed Aug 2026.
MODELS = [
    ("Qwen3-4B (dense)", 4.0, 4.0, "Q4_K_M", (36, 8, 128),
     "any 8\\,GB laptop/PC, CPU", "owned / \\$0"),
    ("gpt-oss-20B (MoE)", 20.9, 3.6, "MXFP4", (24, 8, 128),
     "used 16\\,GB GPU or 16\\,GB PC", "$\\approx$\\$550"),
    ("Qwen3-30B-A3B (MoE)", 30.5, 3.3, "Q4_K_M", (48, 4, 128),
     "32\\,GB mini-PC (CPU) or used 24\\,GB GPU", "\\$650--800"),
]


def kv_gb(layers, kv_heads, head_dim, ctx=CTX, kv_bits=8):
    return 2 * layers * ctx * kv_heads * head_dim * (kv_bits / 8) / 1e9


def rows():
    out = []
    for name, tot, act, q, (l, kvh, hd), hw, cost in MODELS:
        w = tot * BPW[q] / 8
        kv = kv_gb(l, kvh, hd)
        out.append({
            "model": name, "quant": q,
            "weights_gb": round(w, 1), "kv_gb": round(kv, 1),
            "footprint_gb": round(w + kv + OVERHEAD_GB, 1),
            "active_b": act, "hardware": hw, "cost": cost,
        })
    return out


def write_csv(rs):
    os.makedirs(RESULTS, exist_ok=True)
    cols = ["model", "quant", "weights_gb", "kv_gb", "footprint_gb", "active_b"]
    with open(os.path.join(RESULTS, "hardware.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rs)


def write_tex(rs):
    os.makedirs(PAPER_TABLES, exist_ok=True)
    lines = [
        "% AUTO-GENERATED by eval/calc_hardware.py -- do not edit",
        "\\begin{table*}[t]", "\\centering", "\\small",
        "\\caption{Inference hardware floor. Memory footprint is computed "
        "(weights at the listed quantization $+$ an 8k-token KV cache $+$ "
        "runtime overhead) and matches published GGUF sizes. `Active' is the "
        "parameters computed per token, which for the mixture-of-experts models "
        "is far below the resident total, so the 30B-class model runs at "
        "interactive speed on a CPU. Costs are approximate US used/consumer "
        "prices surveyed in August~2026 for the cheapest sufficient hardware; "
        "the 2026 AI-driven memory and GPU shortage has raised them from earlier "
        "lows, yet the floor stays within a few hundred dollars.}",
        "\\label{tab:hardware-floor}",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{lrrll}", "\\hline",
        "\\textbf{Model} & \\textbf{Mem} & \\textbf{Active} & "
        "\\textbf{Cheapest hardware} & \\textbf{Cost} \\\\", "\\hline",
    ]
    for r in rs:
        lines.append(
            f"{r['model']} & {r['footprint_gb']}\\,GB & {r['active_b']}\\,B & "
            f"{r['hardware']} & {r['cost']} \\\\")
    lines += ["\\hline", "\\end{tabular}", "\\end{table*}", ""]
    with open(os.path.join(PAPER_TABLES, "hardware_floor.tex"), "w") as f:
        f.write("\n".join(lines))


def main():
    rs = rows()
    write_csv(rs)
    write_tex(rs)
    for r in rs:
        print(f"  {r['model']:22} footprint={r['footprint_gb']}GB "
              f"active={r['active_b']}B -> {r['cost']}")
    print("calc_hardware: hardware.csv + hardware_floor.tex written")


if __name__ == "__main__":
    main()
