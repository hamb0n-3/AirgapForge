#!/usr/bin/env python3
import csv
import glob
import json
import os

import config

METRICS = {
    "cybermetric": ("accuracy", "CyberMetric"),
    "safety": ("refusal_rate", "Refusal"),
    "safety_asr": ("attack_success_rate", "ASR"),
    "quality": ("mean_score", "Quality"),
}


def load_metric(metric_dir):
    out = {}
    for path in glob.glob(os.path.join(config.RESULTS_DIR, metric_dir, "*.json")):
        d = json.load(open(path))
        out[d["key"]] = d
    return out


def main():
    cyber = load_metric("cybermetric")
    safety = load_metric("safety")
    quality = load_metric("quality")
    keys = sorted(set(cyber) | set(safety) | set(quality))

    rows = []
    for k in keys:
        rows.append({
            "config": k,
            "variant": "finetuned" if k.endswith("-ft") else "base",
            "accuracy": cyber.get(k, {}).get("accuracy"),
            "refusal_rate": safety.get(k, {}).get("refusal_rate"),
            "attack_success_rate": safety.get(k, {}).get("attack_success_rate"),
            "mean_quality": quality.get(k, {}).get("mean_score"),
            "gen_fail_rate": safety.get(k, {}).get("generation_failure_rate"),
        })

    os.makedirs(config.RESULTS_DIR, exist_ok=True)
    with open(os.path.join(config.RESULTS_DIR, "results.json"), "w") as f:
        json.dump(rows, f, indent=2)

    cols = ["config", "variant", "accuracy", "refusal_rate",
            "attack_success_rate", "mean_quality", "gen_fail_rate"]
    with open(os.path.join(config.RESULTS_DIR, "results.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)

    def fmt(v, pct=False):
        if v is None:
            return "--"
        return f"{v*100:.1f}" if pct else f"{v:.2f}"

    LABELS = [
        ("qwen3-4b", "Qwen3-4B", "aligned"),
        ("qwen3-4b", "Qwen3-4B", "abliterated"),
        ("qwen3-30b", "Qwen3-30B", "aligned"),
        ("qwen3-30b", "Qwen3-30B", "abliterated"),
        ("gpt-oss-20b", "gpt-oss-20B", "aligned"),
        ("gpt-oss-20b", "gpt-oss-20B", "abliterated"),
    ]
    by_cfg = {r["config"]: r for r in rows}

    tex = ["% AUTO-GENERATED by eval/aggregate.py -- do not edit",
           "\\begin{table*}[t]", "\\centering", "\\small",
           "\\caption{Capability--safety evaluation matrix. Capability is "
           "CyberMetric-500 accuracy (\\%); safety is refusal rate and "
           "attack-success rate (ASR, \\%) on held out exploit requests; quality "
           "is the abliterated-judge audit score (1--5). For each base model we "
           "report the model as-is and after offensive fine-tuning (ft). Higher "
           "accuracy/quality and higher refusal are safer directions; higher ASR "
           "is more dangerous. $^{\\dagger}$ computed over valid generations "
           "(25.3\\% generation-failure rate, see text).}",
           "\\label{tab:eval-matrix}",
           "\\begin{tabular}{llcccc}", "\\hline",
           "\\textbf{Model} & \\textbf{Align.} & \\textbf{CyberMetric} & "
           "\\textbf{Refusal} & \\textbf{ASR} & \\textbf{Quality} \\\\", "\\hline"]
    for key, label, align in LABELS:
        for variant, suffix, vlabel in [("base", "", ""), ("ft", "-ft", " +ft")]:
            cfg_key = f"{key}-{align}{suffix}"
            r = by_cfg.get(cfg_key)
            if not r:
                continue
            dag = "$^{\\dagger}$" if (r.get("gen_fail_rate") or 0) > 0.05 else ""
            name = label if variant == "base" else ""
            tex.append(
                f"{name} & {align}{vlabel} & {fmt(r['accuracy'], pct=True)} & "
                f"{fmt(r['refusal_rate'], pct=True)}{dag} & "
                f"{fmt(r['attack_success_rate'], pct=True)} & "
                f"{fmt(r['mean_quality'])} \\\\")
        tex.append("\\hline")
    tex += ["\\end{tabular}", "\\end{table*}", ""]
    with open(os.path.join(config.RESULTS_DIR, "results.tex"), "w") as f:
        f.write("\n".join(tex))

    print(f"aggregate: {len(rows)} configs -> results.json/.csv/.tex")
    for r in rows:
        print(f"  {r['config']:26} acc={r['accuracy']} ref={r['refusal_rate']} "
              f"asr={r['attack_success_rate']} qual={r['mean_quality']}")


if __name__ == "__main__":
    main()
